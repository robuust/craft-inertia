<?php

declare(strict_types=1);

namespace Robuust\CraftInertia\Types;

use CraftCms\Cms\Field\Contracts\FieldInterface;
use InvalidArgumentException;

/** Builds TypeScript declarations for the native public page contract. */
final class TypeScriptGenerator
{
    /** Identifies declarations that the generator owns. */
    public const string MARKER = '// Generated by Craft Inertia. Do not edit.';

    /** Shared native page and field declarations referenced by each layout. */
    private const string DECLARATIONS = <<<'TYPESCRIPT'
    export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };

    export type EmptyFields = [];

    export interface NativeEntry<Handle extends string, Fields> {
        id: number | null;
        uid: string | null;
        canonicalId: number | null;
        title: string | null;
        slug: string | null;
        url: string | null;
        postDate: string | null;
        type: Handle;
        fields: Fields;
    }

    export type RelatedEntry<Handle extends string = string> = Handle extends keyof EntryFieldsByType
        ? NativeEntry<Handle, EntryFieldsByType[Handle] | EmptyFields>
        : NativeEntry<Handle, Record<string, unknown> | EmptyFields>;

    export type MatrixEntry<Handle extends string> = RelatedEntry<Handle> | RelatedEntry;

    export type ProjectedEntry<Handle extends string> = Handle extends keyof EntryFieldsByType
        ? NativeEntry<Handle, EntryFieldsByType[Handle]>
        : RelatedEntry<Handle>;

    export interface NativeSite {
        id: number | null;
        uid: string | null;
        handle: string;
        name: string;
        language: string;
        baseUrl: string | null;
    }

    export interface NativeHead {
        title: string;
        meta: Record<string, string>[];
        link: Record<string, string>[];
        jsonLd: { key: string; content: string }[];
        robots: string;
    }

    export interface NativePageProps<Handle extends string = keyof EntryFieldsByType extends never ? string : keyof EntryFieldsByType> {
        entry: ProjectedEntry<Handle>;
        site: NativeSite;
        preview: boolean;
        head: NativeHead;
        [prop: string]: unknown;
    }

    export interface NativeOption {
        value: string | null;
        label: string | null;
    }

    export interface NativeLink {
        url: string;
        label: string | null;
        target: string | null;
        urlSuffix: string | null;
        attributes: Record<string, JsonValue>;
    }

    export interface NativeAssetVariant {
        url: string | null;
        width: number | null;
        height: number | null;
        srcset: string | false | null;
    }

    export interface NativeAsset {
        id: number | null;
        uid: string | null;
        title: string | null;
        url: string | null;
        width: number | null;
        height: number | null;
        alt: string | null;
        srcset: null;
        variants?: NativeAssetVariant[] | Record<string, NativeAssetVariant>;
    }
    TYPESCRIPT;

    /**
     * @param EntrySchema $schema Effective Craft entry type and field layouts.
     * @param FieldType $fieldType Maps built-in fields to their native declarations.
     */
    public function __construct(
        private readonly EntrySchema $schema,
        private readonly FieldType $fieldType,
    ) {
    }

    /** @return string Deterministic declarations for the applied schema and project settings. */
    public function generate(): string
    {
        $types = $this->schema->fieldsByType();
        $metadata = $this->metadata();
        $serializers = config('craft-inertia.fieldSerializers', []);
        if (!is_array($serializers)) {
            throw new InvalidArgumentException('craft-inertia.fieldSerializers must be an ordered array.');
        }

        ksort($types, SORT_STRING);
        $declarations = [];
        foreach ($types as $type => $layouts) {
            $variants = [];
            foreach ($layouts as $fields) {
                $variants[] = $this->layoutType($fields, $metadata[$type] ?? [], $serializers !== []);
            }
            $variants = array_unique($variants);
            sort($variants, SORT_STRING);
            $handle = json_encode($type, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
            $declarations[] = '    '.$handle.': '.implode(' | ', $variants).';';
        }

        $fields = $declarations === [] ? '' : implode("\n", $declarations)."\n";

        return self::MARKER."\n\n".self::DECLARATIONS."\n\nexport interface EntryFieldsByType {\n".$fields."}\n";
    }

    /**
     * @param array<string, FieldInterface> $fields Public fields for the current effective layout.
     * @param array<string, string> $metadata Explicit type expressions for this entry type.
     * @param bool $usesSerializers Whether any runtime field serializer could change the native shape.
     * @return string Type expression for the JSON field projection.
     */
    private function layoutType(array $fields, array $metadata, bool $usesSerializers): string
    {
        if ($fields === []) {
            return 'EmptyFields';
        }

        ksort($fields, SORT_STRING);
        $members = [];
        foreach ($fields as $handle => $field) {
            $key = json_encode($handle, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
            $type = $metadata[$handle] ?? ($usesSerializers ? 'JsonValue' : $this->fieldType->nativeType($field));
            $members[] = '        '.$key.': '.$type.';';
        }

        return "{\n".implode("\n", $members)."\n    }";
    }

    /** @return array<string, array<string, string>> Project-owned declarations by effective entry type and field. */
    private function metadata(): array
    {
        $metadata = config('craft-inertia.entryFieldTypes', []);
        if (!is_array($metadata)) {
            throw new InvalidArgumentException('craft-inertia.entryFieldTypes must map entry types to field type expressions.');
        }

        foreach ($metadata as $type => $fields) {
            if (!is_string($type) || $type === '' || !is_array($fields)) {
                throw new InvalidArgumentException('craft-inertia.entryFieldTypes must map entry types to field type expressions.');
            }
            foreach ($fields as $handle => $expression) {
                if (!is_string($handle) || $handle === '' || !is_string($expression) || trim($expression) === '') {
                    throw new InvalidArgumentException("craft-inertia.entryFieldTypes.$type must map field handles to non-empty TypeScript expressions.");
                }
            }
        }

        return $metadata;
    }
}
